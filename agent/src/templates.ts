import {
  type AgentSettings,
  type AppSpec,
  hostnames,
  POOL_PATH,
  poolHost,
  projectName,
} from './app-spec.ts'

/** The user pool's container on the `web` network, where Caddy reaches it (ADR 0035). */
export const POOL_UPSTREAM = 'auth:3000'

/**
 * Proxies to the user pool, telling it the visitor's address in a header of Spotcraft's own,
 * set by Caddy so a client can't choose it (the pool limits new guests per address).
 */
const poolProxy = (indent: string) => `${indent}reverse_proxy ${POOL_UPSTREAM} {
${indent}\theader_up X-Spotcraft-Client-IP {client_ip}
${indent}}`

/**
 * Caddy reaches an app's container by this alias on the shared edge network: `app-<service>`,
 * e.g. `app-blog-green` for the green slot of `blog`. (An app deployed before slots has the
 * service `blog`, so `app-blog`.)
 */
export const upstreamAlias = (service: string) => `app-${service}`

/** Compose interpolates `$VAR` even in values; `$$` is a literal dollar sign. */
const escapeCompose = (value: string) => value.replaceAll('$', '$$$$')

/**
 * The app's compose file, with one service: the slot being deployed (ADR 0028). The other
 * slot's container, if any, keeps running until traffic has moved. Written as JSON (valid YAML),
 * so values never need YAML escaping. Hardened by default: no capabilities, no privilege
 * escalation, resource limits.
 */
export function renderCompose(
  app: AppSpec,
  service: string,
  /** The env Spotcraft gives the app (ADR 0034); it wins over `app.env`. */
  platformEnv: Record<string, string> = {},
): string {
  const all = { ...app.env, ...platformEnv }
  const env = Object.fromEntries(
    Object.entries(all).map(([key, value]) => [key, escapeCompose(value)]),
  )
  const definition: Record<string, unknown> = {
    image: `${app.image}:${app.tag}`,
    restart: 'unless-stopped',
    environment: env,
    networks: { edge: { aliases: [upstreamAlias(service)] } },
    cap_drop: ['ALL'],
    security_opt: ['no-new-privileges:true'],
    mem_limit: app.memory,
    cpus: app.cpus,
    pids_limit: 256,
    // Docker sends SIGTERM and waits this long before killing it: time for the old slot to
    // finish the requests it already has once traffic has moved.
    stop_grace_period: '30s',
    logging: { driver: 'json-file', options: { 'max-size': '10m', 'max-file': '3' } },
  }
  if (app.readOnly) {
    definition.read_only = true
    definition.tmpfs = ['/tmp:size=64m,noexec,nosuid,nodev']
  }
  const compose = {
    name: projectName(app.name),
    services: { [service]: definition },
    networks: { edge: { name: 'spotcraft-edge', external: true } },
  }
  return `${JSON.stringify(compose, null, 2)}\n`
}

/** The service a compose file written by `renderCompose` runs: the app's live slot. */
export function composeService(compose: string): string | undefined {
  const services = (JSON.parse(compose) as { services?: Record<string, unknown> }).services
  return services ? Object.keys(services)[0] : undefined
}

/**
 * Whether `www.<domain>` should redirect to the domain: only for a registrable root like
 * `tagtape.app`. A subdomain (`app.example.com`) gets no `www.` site, which would otherwise
 * make Caddy request a certificate for a name nobody points at the server.
 */
export const wantsWwwRedirect = (domain: string) => domain.split('.').length === 2

/**
 * The app's Caddy site block, imported by the server's main Caddyfile. It answers on the
 * app's default host and its custom domain, and proxies to `service`, the app's live slot.
 * Behind Cloudflare (`edge: cloudflare`) the sites are plain HTTP: Cloudflare terminates TLS
 * and the tunnel brings requests to Caddy on port 80.
 */
export function renderSite(
  app: AppSpec,
  settings: AgentSettings,
  service: string,
  /** The app's Umami website (ADR 0038); without one, nothing is counted. */
  websiteId?: string,
): string {
  const scheme = settings.edge === 'cloudflare' ? 'http://' : ''
  const hosts = hostnames(app, settings.appsDomain)
  // E.g. APPS_DOMAIN was cleared and the app has no domain of its own: no site, rather than a
  // block with an empty address that would make Caddy reject the whole configuration.
  if (hosts.length === 0) {
    return `# Generated by the Spotcraft agent for "${app.name}": it has no address. Set APPS_DOMAIN or give it a domain.\n`
  }
  const www =
    app.domain && wantsWwwRedirect(app.domain)
      ? `
${scheme}www.${app.domain} {
\tredir https://${app.domain}{uri} permanent
}
`
      : ''
  return `# Generated by the Spotcraft agent for "${app.name}"; changes are overwritten on deploy.
${hosts.map((host) => scheme + host).join(', ')} {
\tencode zstd gzip
\theader {
\t\tStrict-Transport-Security "max-age=31536000; includeSubDomains"
\t\tX-Content-Type-Options "nosniff"
\t\tReferrer-Policy "strict-origin-when-cross-origin"
\t\t# Defaults: sent only when the app doesn't send its own. CSP is the app's to set.
\t\t?X-Frame-Options "DENY"
\t\t?Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=(), usb=()"
\t\t?Cross-Origin-Opener-Policy "same-origin"
\t\t-Server
\t}
\t# The instance's user pool, on the app's own domain (ADR 0035).
\thandle ${POOL_PATH}/* {
${poolProxy('\t\t')}
\t}
${analyticsRoutes(app, websiteId)}
\thandle {
\t\treverse_proxy ${upstreamAlias(service)}:${app.port} {
\t\t\t# The visitor's address (Cloudflare's CF-Connecting-IP when behind the tunnel), not a hop's.
\t\t\theader_up X-Forwarded-For {client_ip}${injection(app, websiteId)}
\t}
}
${www}`
}

/** Analytics' container on the `web` network, where Caddy reaches it (ADR 0038). */
export const ANALYTICS_UPSTREAM = 'umami:3000'

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/

/** Whether the app's pages get the tracker: it has a website and its switch isn't off. */
export const isAnalyticsOn = (app: AppSpec, websiteId: string | undefined): websiteId is string =>
  app.analytics !== false && websiteId !== undefined && UUID.test(websiteId)

/**
 * What every app's site serves for analytics (ADR 0038): Umami's tracker and collect endpoint,
 * the app's settings for clients that send their own events, and the privacy page.
 */
function analyticsRoutes(app: AppSpec, websiteId: string | undefined): string {
  const on = isAnalyticsOn(app, websiteId)
  const config = JSON.stringify({
    analytics: on ? { websiteId, enabled: true } : { enabled: false },
  })
  const page = privacyPage(app.name, on)
    .split('\n')
    .map((line) => `\t\t${line}`)
    .join('\n')
  return `\t# Analytics (ADR 0038): Umami's tracker and collect endpoint, the app's settings, and
\t# what is counted.
\thandle /_spotcraft/s.js {
\t\treverse_proxy ${ANALYTICS_UPSTREAM}
\t}
\thandle /_spotcraft/e {
\t\treverse_proxy ${ANALYTICS_UPSTREAM} {
\t\t\theader_up X-Spotcraft-Client-IP {client_ip}
\t\t}
\t}
\thandle /_spotcraft/config.json {
\t\theader Content-Type "application/json"
\t\theader Cache-Control "public, max-age=300"
\t\trespond \`${config}\` 200
\t}
\thandle /_spotcraft/privacy {
\t\theader Content-Type "text/html; charset=utf-8"
\t\theader Content-Security-Policy "default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'"
\t\trespond <<HTML
${page}
\t\tHTML 200
\t}`
}

/**
 * With analytics on, the app is asked for uncompressed responses (Caddy's `encode` compresses
 * them for the visitor), and its HTML gets the tracker before `</head>`, streamed so pages
 * rendered on the server still stream. Returns the end of the `reverse_proxy` block.
 */
function injection(app: AppSpec, websiteId: string | undefined): string {
  if (!isAnalyticsOn(app, websiteId)) return '\n\t\t}'
  const tag = `<script defer src="/_spotcraft/s.js" data-website-id="${websiteId}"></script>`
  return `
\t\t\t# Plain HTML, so the tracker can be added below.
\t\t\theader_up Accept-Encoding identity
\t\t}
\t\treplace stream {
\t\t\tmatch {
\t\t\t\theader Content-Type text/html*
\t\t\t}
\t\t\t</head> \`${tag}</head>\`
\t\t}`
}

/**
 * The privacy page every app domain serves at /_spotcraft/privacy: what Spotcraft counts, and a
 * switch that turns counting off in this browser (Umami's own `umami.disabled` flag).
 */
function privacyPage(name: string, on: boolean): string {
  const counted = on
    ? `<p>This site counts its visits with <a href="https://umami.is">Umami</a>, on its own server. It sets no cookies and stores no IP address or anything else that identifies you: only the page, where the visit came from, the country, and the browser, system and screen size. Apps that use this site count the screens they show, with their version and platform, the same way.</p>
<p><label><input type="checkbox" id="off"> Don't count my visits in this browser</label></p>
<script>
const off = document.getElementById('off')
off.checked = localStorage.getItem('umami.disabled') === '1'
off.onchange = () => off.checked ? localStorage.setItem('umami.disabled', '1') : localStorage.removeItem('umami.disabled')
</script>`
    : '<p>This site counts nothing about its visits.</p>'
  return `<!doctype html>
<html lang="en">
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Privacy: ${name}</title>
<style>body { font: 17px/1.5 system-ui, sans-serif; max-width: 36rem; margin: 3rem auto; padding: 0 1rem }</style>
<h1>What ${name} counts</h1>
${counted}
<p><a href="/">Back to the site</a></p>
</html>`
}

/**
 * The user pool's own site, `auth.<APPS_DOMAIN>`, for clients without an app domain (Expo apps,
 * sites not on Spotcraft): `/main/*` is the pool `main` (ADR 0035). Written as
 * `sites/_auth.caddy`; without an apps domain there is no such host, and no site.
 */
export function renderPoolSite(settings: AgentSettings): string {
  if (!settings.appsDomain) {
    return '# Generated by the Spotcraft agent: the user pool has no host of its own without APPS_DOMAIN.\n'
  }
  const scheme = settings.edge === 'cloudflare' ? 'http://' : ''
  return `# Generated by the Spotcraft agent for the user pool; changes are overwritten.
${scheme}${poolHost(settings.appsDomain)} {
\theader {
\t\tStrict-Transport-Security "max-age=31536000; includeSubDomains"
\t\tX-Content-Type-Options "nosniff"
\t\t-Server
\t}
\thandle_path /main/* {
\t\trewrite * ${POOL_PATH}{uri}
${poolProxy('\t\t')}
\t}
\thandle {
\t\trespond 404
\t}
}
`
}
